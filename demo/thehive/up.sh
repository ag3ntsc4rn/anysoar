#!/usr/bin/env bash
# Start the local TheHive + Cortex lab. On first run, generates per-install secrets into
# .env.local, then sets both up: TheHive gets an "anysoar" organisation and service account
# with an API key, Cortex gets an organisation, an API key for TheHive and three key-free
# analyzers, and TheHive is connected to Cortex. Later runs just start the containers.
set -euo pipefail
cd "$(dirname "$0")"

env_file=.env.local
random() { LC_ALL=C tr -dc 'A-Za-z0-9' </dev/urandom | head -c "$1"; }
die() { echo "up.sh: $*" >&2; exit 1; }

if [[ ! -f $env_file ]]; then
  umask 077
  cat >"$env_file" <<EOF
# Generated by up.sh for this machine only. Do not commit.
THEHIVE_SECRET=$(random 48)
THEHIVE_ADMIN_PASSWORD=$(random 24)
THEHIVE_ANALYST_PASSWORD=$(random 24)
CORTEX_ADMIN_PASSWORD=$(random 24)
EOF
  echo "Generated $PWD/$env_file"
fi
mkdir -p .cortex-jobs

set -a
# shellcheck source=/dev/null
source "$env_file"
CORTEX_JOB_DIR=$PWD/.cortex-jobs  # analyzer jobs; must be the same path in Cortex and here
set +a
thehive="http://127.0.0.1:${THEHIVE_PORT:-9000}/api"
cortex="http://127.0.0.1:${CORTEX_PORT:-9001}/api"
org=anysoar
service_user=anysoar@anysoar.lab  # what the driver uses
analyst=analyst@anysoar.lab        # for people to log in to the web UI
# Key-free analyzers for the indicator types anysoar sends. They look indicators up in public
# services (DShield, RIPEstat and friends, CIRCL hashlookup); their images run natively on
# arm64 and amd64.
analyzers=(DShield_lookup_1_0 Abuse_Finder_3_0 CIRCLHashlookup_1_1)

docker compose --env-file "$env_file" up -d

wait_for() {  # wait_for <name> <url>
  printf 'Waiting for %s' "$1"
  for _ in $(seq 1 90); do
    curl -sf "$2" >/dev/null 2>&1 && { echo; return; }
    printf '.'
    sleep 5
  done
  echo
  die "$1 did not come up; see: docker compose logs"
}
wait_for TheHive "$thehive/status"
wait_for Cortex "$cortex/status"

# call <expected status> <curl args...>: run curl, fail unless it answers with that status,
# and print the body.
call() {
  local expected=$1 body status
  shift
  body=$(curl -s -w '\n%{http_code}' -H 'Content-Type: application/json' "$@")
  status=${body##*$'\n'}
  body=${body%$'\n'*}
  [[ $status == "$expected" ]] || die "${*: -1} answered $status, expected $expected: ${body:0:300}"
  printf '%s' "$body"
}

set_up_cortex() {
  echo "Setting up Cortex"
  local admin=(-u "admin:$CORTEX_ADMIN_PASSWORD")
  call 204 -X POST "$cortex/maintenance/migrate" -d '{}' >/dev/null
  # Cortex accepts the first user without authentication.
  call 201 -X POST "$cortex/user" -d "$(jq -n --arg p "$CORTEX_ADMIN_PASSWORD" \
    '{login: "admin", name: "Cortex admin", roles: ["superadmin"], organization: "cortex", password: $p}')" >/dev/null
  call 201 "${admin[@]}" -X POST "$cortex/organization" \
    -d "{\"name\": \"$org\", \"description\": \"anysoar lab\", \"status\": \"Active\"}" >/dev/null
  call 201 "${admin[@]}" -X POST "$cortex/user" \
    -d "{\"login\": \"thehive\", \"name\": \"TheHive\", \"roles\": [\"read\", \"analyze\", \"orgadmin\"], \"organization\": \"$org\"}" >/dev/null
  CORTEX_API_KEY=$(call 200 "${admin[@]}" -X POST "$cortex/user/thehive/key/renew")
  for analyzer in "${analyzers[@]}"; do
    call 201 -H "Authorization: Bearer $CORTEX_API_KEY" -X POST "$cortex/organization/analyzer/$analyzer" \
      -d "{\"name\": \"$analyzer\", \"configuration\": {\"check_tlp\": true, \"max_tlp\": 2, \"check_pap\": true, \"max_pap\": 2, \"auto_extract_artifacts\": false}, \"jobCache\": 10, \"jobTimeout\": 5}" >/dev/null
  done
  echo "CORTEX_API_KEY=$CORTEX_API_KEY" >>"$env_file"
}

set_up_thehive() {
  echo "Setting up TheHive"
  local admin=(-u "admin@thehive.local:$THEHIVE_ADMIN_PASSWORD")
  # Replace the well-known default password before anything else.
  call 204 -u admin@thehive.local:secret -X POST "$thehive/v1/user/admin@thehive.local/password/set" \
    -d "$(jq -n --arg p "$THEHIVE_ADMIN_PASSWORD" '{password: $p}')" >/dev/null
  call 201 "${admin[@]}" -X POST "$thehive/v1/organisation" \
    -d "{\"name\": \"$org\", \"description\": \"anysoar lab\"}" >/dev/null
  call 201 "${admin[@]}" -X POST "$thehive/v1/user" \
    -d "{\"login\": \"$service_user\", \"name\": \"anysoar\", \"profile\": \"analyst\", \"organisation\": \"$org\", \"type\": \"Service\"}" >/dev/null
  call 201 "${admin[@]}" -X POST "$thehive/v1/user" \
    -d "$(jq -n --arg l "$analyst" --arg o "$org" --arg p "$THEHIVE_ANALYST_PASSWORD" \
      '{login: $l, name: "Lab analyst", profile: "analyst", organisation: $o, password: $p}')" >/dev/null
  THEHIVE_API_KEY=$(call 200 "${admin[@]}" -X POST "$thehive/v1/user/$service_user/key/renew")
  call 204 "${admin[@]}" -H 'X-Organisation: admin' -X PUT "$thehive/v1/admin/config/cortex" \
    -d "$(jq -n --arg k "$CORTEX_API_KEY" '{
      statusCheckInterval: "1 minute", refreshDelay: "5 seconds", maxRetryOnError: 3,
      jobTimeout: "10 minutes",
      servers: [{name: "Cortex", url: "http://cortex:9001", auth: {type: "bearer", key: $k},
                 includedTheHiveOrganisations: ["*"], excludedTheHiveOrganisations: [],
                 wsConfig: {}}]}')" >/dev/null
  echo "THEHIVE_API_KEY=$THEHIVE_API_KEY" >>"$env_file"
}

if [[ -z ${CORTEX_API_KEY:-} ]]; then set_up_cortex; fi
if [[ -z ${THEHIVE_API_KEY:-} ]]; then set_up_thehive; fi

status=$(curl -s -o /dev/null -w '%{http_code}' -H "Authorization: Bearer $THEHIVE_API_KEY" "$thehive/v1/user/current")
[[ $status == 200 ]] || die "TheHive rejected the API key in $env_file (HTTP $status). If the data was deleted without it, reset the lab: ./down.sh --purge && ./up.sh"

# TheHive runs on a trial license that expires two weeks after the first start; after that it
# is read-only. See "Trial license" in README.md.
expires=$(curl -s -u "admin@thehive.local:$THEHIVE_ADMIN_PASSWORD" "$thehive/v1/license/current" \
  | jq -r '(.license // .fallback).expiresAt // empty')
trial=""
if [[ -n $expires ]]; then
  days=$(( (expires / 1000 - $(date +%s)) / 86400 ))
  if (( days < 0 )); then
    trial="  License: the trial has EXPIRED and TheHive is read-only; reset with ./down.sh --purge && ./up.sh"
  else
    trial="  License: trial, $days days left"
  fi
fi

cat <<EOF

TheHive and Cortex are running.
  TheHive: http://localhost:${THEHIVE_PORT:-9000}  (user: $analyst)
  Cortex:  http://localhost:${CORTEX_PORT:-9001}  (user: admin)
  Passwords are in $PWD/$env_file
$trial

For anysoar's TheHive driver:
  export THEHIVE_URL=http://127.0.0.1:${THEHIVE_PORT:-9000}
  export THEHIVE_API_KEY="\$(grep ^THEHIVE_API_KEY= $PWD/$env_file | cut -d= -f2)"

Stop with ./down.sh (add --purge to delete its data and secrets).
EOF
